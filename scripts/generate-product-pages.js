// Trim a string to <=budget at a word boundary (no mid-word cuts).
function capWords(str, budget) {
  if (budget <= 0) return '';
  if (str.length <= budget) return str.trim();
  let s = str.slice(0, budget);
  const sp = s.lastIndexOf(' ');
  if (sp > budget * 0.5) s = s.slice(0, sp);
  return s.trim();
}

function tokenValue(p, type) {
  const n = p.name;
  if (type === 'speed') { const s = parseSpeed(n); return s ? s + 'MHz' : null; }
  if (type === 'cl') { const m = n.match(/\bCL\s?(\d{2})\b/i); return m ? 'CL' + m[1] : null; }
  if (type === 'color') { const m = n.match(/\b(Black|White|Gray|Grey|Silver|Green|Blue|Red|Royal)\b/i); return m ? m[1] : null; }
  if (type === 'heatsink') {
    if (/non-?heatsink|without heatsink|w\/o heatsink/i.test(n)) return 'No Heatsink';
    if (/heatsink/i.test(n)) return 'Heatsink';
    return null;
  }
  if (type === 'pack') { const m = n.match(/(\d+)[\s-]?pack/i); return m ? m[1] + '-Pack' : null; }
  // Capacity is the single most useful differentiator for a shopper and is
  // fully parseable, but shortName() often truncates before it (it cuts at the
  // first parenthesis), so siblings that differ only by size used to collide
  // and fall through to the ASIN fallback. R1 added it.
  if (type === 'capacity') return capacityLabel(totalCapacityGB(n));
  // Kit configuration separates a 1x16GB module from a 2x8GB kit at the same
  // total capacity, which is a different product to a builder (one DIMM slot
  // vs two). Already parsed for the capacity math, so it costs nothing.
  if (type === 'kit') { const k = parseKitConfig(n); return k ? k.replace(/x(\d+)$/, 'x$1GB') : null; }
  if (type === 'formfactor') return formFactor(n);
  return null;
}
