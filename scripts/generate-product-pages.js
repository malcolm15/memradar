// Buy-indicator / value-metric thresholds — SINGLE SOURCE. Used for the baked
// HTML here AND baked into each page's #pdpHydrateConfig so pdp-hydrate.js
// recomputes against the live price with identical values (no magic-number
// duplication in the browser).
const BUY_GOOD_MAX_RATIO = 1.01; // current <= avg90 * this => "good time to buy"
const VALUE_LOW_RATIO = 0.93;    // $/GB < median * this => "good value"
const VALUE_HIGH_RATIO = 1.07;   // $/GB > median * this => "above the median"
const INFLATION_ATL_RATIO = 1.5; // Price Analysis honest-flag: a "good" price that
                                 // is still >= this x the all-time low reads as
                                 // "near its recent low but well above where it
                                 // traded a year or two ago" (the memflation reality).

// Single predicate behind BOTH the buy-indicator and the Price-Analysis verdict,
// so they can never disagree. Returns 'good' | 'typical' | 'elevated' | null.
// Mirrors the buy-indicator exactly: <= avg90*ratio is good/typical (typical when
// within 1% of the average), else elevated. pdp-hydrate.js has the identical fn.
function buyState(current, avg90) {
  if (avg90 == null) return null;
  const pct = Math.round(Math.abs(((current - avg90) / avg90) * 100));
  if (current <= avg90 * BUY_GOOD_MAX_RATIO) return pct <= 1 ? 'typical' : 'good';
  return 'elevated';
}

