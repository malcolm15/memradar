// Top N products in a category closest to their all-time low, in stock at
// every retailer we list for them. OOS products are excluded outright:
// recommending an unbuyable item is the same failure as claiming an
// unbuyable price. Category-parameterised so both guides share one ranking.
function nearAtl(products, neweggBySku, category, limit = 6) {
  const rows = [];
  for (const p of products) {
    if (p.category !== category || !p.stats || !p.stats.atl) continue;
    if (p.inStock === false) continue;                       // Amazon OOS
    const ng = neweggBySku.get(p.sku);
    if (ng && ng.in_stock === false) continue;               // Newegg OOS
    const cur = p.stats.current, atl = p.stats.atl.price;
    if (!(cur > 0) || !(atl > 0)) continue;
    rows.push({ p, cur, atl, gap: ((cur - atl) / atl) * 100 });
  }
  rows.sort((a, b) => a.gap - b.gap);
  return rows.slice(0, limit);
}

