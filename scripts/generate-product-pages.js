// HAND-CURATED NAME OVERRIDES. These beat the automatic builder entirely.
// Populated only where every parsed attribute fails to separate siblings and the
// automatic path would otherwise emit an ASIN fragment, which must never ship as
// a user-facing name. Each entry is read off the raw listing title by a human.
const TITLE_OVERRIDES = require('./title-overrides.js');

const TOKEN_TYPES = ['capacity', 'kit', 'speed', 'cl', 'color', 'heatsink', 'pack', 'formfactor'];
function assignTokens(grp) {
  // 1) a single parsed attribute that is present on every member and distinct
  //    across all of them.
  for (const type of TOKEN_TYPES) {
    const vals = grp.map((p) => tokenValue(p, type));
    if (vals.every(Boolean) && new Set(vals).size === grp.length) {
      vals.kind = type;
      return vals;
    }
  }
  // 2) a PAIR of parsed attributes. Siblings frequently share one axis and
  //    differ on another (same capacity, different CL; same speed, different
  //    size), so "32GB CL30" separates what neither half can. Still entirely
  //    derived from parsed specs - no guessing.
  for (let i = 0; i < TOKEN_TYPES.length; i++) {
    for (let j = i + 1; j < TOKEN_TYPES.length; j++) {
      const a = grp.map((p) => tokenValue(p, TOKEN_TYPES[i]));
      const b = grp.map((p) => tokenValue(p, TOKEN_TYPES[j]));
      if (!a.every(Boolean) || !b.every(Boolean)) continue;
      const combo = a.map((v, k) => `${v} ${b[k]}`);
      if (new Set(combo).size === grp.length) {
        combo.kind = `${TOKEN_TYPES[i]}+${TOKEN_TYPES[j]}`;
        return combo;
      }
    }
  }
  // FALLBACK: no parsed attribute separates these products, so the last 4 of
  // the ASIN is used. That is a machine token, not a spec, and it reads as a
  // typo in a heading ("CORSAIR Vengeance RGB RS DDR5 9NR3"). R1 rule: these
  // are FLAGGED at the gate for a human ruling rather than silently shipped,
  // because guessing a distinguishing attribute is worse than admitting we
  // could not parse one. See the dry run's AMBIGUOUS SIBLINGS report.
  const vals = grp.map((p) => p.sku.slice(-4));
  vals.kind = 'asin';
  return vals;
}
function groupBy(arr, keyFn) {
  const m = new Map();
  arr.forEach((x) => { const k = keyFn(x); (m.get(k) || m.set(k, []).get(k)).push(x); });
  return [...m.values()];
}

// META DESCRIPTION, built from this product's real numbers (R1). Clauses are
// added in priority order until the description clears DESC_MIN, and stop
// before DESC_TARGET. Every clause is a fact about THIS product, so two pages
// only match if their data matches. Clauses whose data is missing or not
// trustworthy (see MIN_POINTS_* gates) are skipped rather than faked, which is
// why the assembly is greedy instead of a fixed template: a page with no
// 90-day average still has to reach 120 characters honestly.
//
// No em dashes (standing copy rule).
function buildDesc(p, token, hasNewegg) {
  const s = p.stats;
  const tok = token ? ' ' + token : '';
  const retailers = hasNewegg ? 'Amazon and Newegg' : 'Amazon';

  const clauses = [];
  clauses.push(`${money(s.current)} now`);
  if (s.avg90 != null) {
    const pct = Math.round(Math.abs(((s.current - s.avg90) / s.avg90) * 100));
    clauses.push(pct < 2 ? 'in line with its 90-day average'
      : `${pct}% ${s.current < s.avg90 ? 'below' : 'above'} its 90-day average`);
  }
  if (s.extremesOk && s.atl && s.ath && s.ath.price > s.atl.price) {
    clauses.push(`all-time low ${money(s.atl.price)}`);
  }
  clauses.push(`${s.days} days of tracked prices`);
  clauses.push(`compared at ${retailers}`);
  clauses.push('free price-drop alerts');

  // Name budget shrinks until the ESCAPED result fits. Names carrying a quote
  // render as &#39; (6 chars for 1), so budgeting against raw length silently
  // overshoots the band; that bug already shipped once.
  // Use _titleName, the SAME string as the h1 and <title>. Building the
  // description from a bare shortName() instead let a collision sibling's
  // description say "CORSAIR Vengeance RGB RS DDR5 RAM" while its h1 said
  // "CORSAIR Vengeance RGB 32GB 6000MHz": the distinguishing attribute the
  // whole R1 naming rule exists to surface was missing from the one field
  // Google actually shows under the title.
  // Try every name budget from the full name down, and take the FIRST result
  // that lands inside [DESC_MIN, DESC_TARGET]. A shorter name frees characters
  // for one more clause, which is what rescues a description that would
  // otherwise stop under the floor because the next clause did not fit. If no
  // budget lands in band (a very long name with very short clauses), keep the
  // longest result that at least respects the ceiling.
  let best = null;
  for (let budget = TITLE_NAME_BUDGET; budget >= 6; budget -= 1) {
    const name = capWords(p._titleName, budget) + tok;
    let body = '';
    for (const c of clauses) {
      const next = body ? body + ', ' + c : c;
      if (esc(`${name}: ${next}.`).length > DESC_TARGET) break;
      body = next;
      // FLOOR is measured on the RAW string, CEILING on the escaped one. Google
      // counts the rendered text, so the 120 floor is about what a reader sees;
      // the 158 ceiling is about the HTML attribute not overrunning. A name
      // containing quotes (2.5'' -> &#39;&#39;) makes the two differ by a lot,
      // and testing the floor against the escaped length wrongly accepted a
      // 117-character description as in-band.
      if (`${name}: ${body}.`.length >= DESC_MIN) break;
    }
    const out = `${name}: ${body}.`;
    if (esc(out).length > DESC_TARGET) continue;
    if (out.length >= DESC_MIN) return out;
    if (!best || out.length > best.length) best = out;
  }
  return best || `${capWords(p._titleName, 40)}: ${clauses[0]}.`;
}

// Compute unique, in-band pageTitle + pageDesc for every product (mutates).
function computePageMeta(products, neweggBySku) {
  // Titles: base = shortName capped to the name budget; dedup collisions with tokens.
  // Relisting duplicates are excluded from disambiguation entirely: they take
  // their canonical's name below. Including them would force the builder to
  // invent a difference between two listings of one product, and can push a
  // whole sibling group onto the ASIN fallback for a distinction that does not
  // exist (it did exactly that to the Trident Z5 Neo group).
  const namable = products.filter((p) => !RELISTINGS[p.sku]);
  groupBy(namable, (p) => p.category + '|' + capWords(displayName(p), H1_NAME_BUDGET)).forEach((grp) => {
    const base = capWords(displayName(grp[0]), H1_NAME_BUDGET);
    if (grp.length === 1) { grp[0]._titleName = base; return; }
    const tokens = assignTokens(grp);
    grp.forEach((p, i) => {
      const tok = tokens[i];
      // Truncate the GROUP KEY, not a fresh cut of shortName. Re-truncating
      // shortName to make room for the token could delete the very substring
      // that separated this group from a sibling group: "Western Digital
      // WD_Black SN7100 2TB NVMe" cut to 31 chars fell back to a word boundary
      // at "Western Digital WD_Black", so the SN7100 and SN8100 groups both
      // emitted "Western Digital WD_Black 2TB". The group key is by definition
      // the string that made this group distinct, so it is the safe base.
      p._titleName = (capWords(base, H1_NAME_BUDGET - tok.length - 1) + ' ' + tok).trim();
      p._titleTokenKind = tokens.kind;
      p._titleToken = tok;
    });
  });
  // Hand-curated overrides win over anything the builder produced.
  namable.forEach((p) => {
    if (TITLE_OVERRIDES[p.sku]) {
      p._titleName = capWords(TITLE_OVERRIDES[p.sku], H1_NAME_BUDGET);
      p._titleTokenKind = 'override';
    }
  });
  // A relisting is the SAME product, so it takes the canonical's name verbatim
  // and is exempt from the uniqueness pass below: rel=canonical already tells
  // search engines these are one page, and inventing a difference in the name
  // would contradict that.
  const bySku = new Map(products.map((p) => [p.sku, p]));
  products.forEach((p) => {
    const canonSku = RELISTINGS[p.sku];
    const canon = canonSku && bySku.get(canonSku);
    if (canon) { p._titleName = canon._titleName; p._relistingOf = canon; }
  });

  // FINAL UNIQUENESS GUARANTEE. Everything above is best-effort readability;
  // this is the invariant. Two PDPs sharing a title is a duplicate-content
  // signal, which is the whole reason R1 exists, so any collision that survives
  // gets the ASIN last-4 and is reported as AMBIGUOUS for a human ruling.
  groupBy(products.filter((p) => !p._relistingOf), (p) => p.category + '|' + p._titleName).forEach((grp) => {
    if (grp.length === 1) return;
    grp.forEach((p) => {
      const tok = p.sku.slice(-4);
      p._titleName = (capWords(p._titleName, H1_NAME_BUDGET - tok.length - 1) + ' ' + tok).trim();
      p._titleTokenKind = 'asin';
      p._titleToken = tok;
    });
  });
  // The <title> is FITTED from the h1 name, dropping non-mandatory words first.
  // h1 and title can therefore differ in length while never disagreeing in fact.
  products.forEach((p) => { p._seoName = fitName(p._titleName, TITLE_NAME_BUDGET, p); });
  // FITTING CAN STILL COLLIDE where two h1s differ only in words the fitter was
  // allowed to drop. Fall back to the untruncated h1 name for the whole group:
  // a title slightly over the soft ceiling beats two identical titles, which is
  // a duplicate-content signal.
  groupBy(products.filter((p) => !p._relistingOf), (p) => p.category + '|' + p._seoName).forEach((grp) => {
    if (grp.length === 1) return;
    grp.forEach((p) => { p._seoName = p._titleName; });
  });
  products.forEach((p) => {
    p.pageTitle = (p._seoName + TITLE_SUFFIX).length <= 60
      ? p._seoName + TITLE_SUFFIX
      : p._seoName + TITLE_SUFFIX_SHORT;
  });

  // Descriptions: dynamic name budget per product; then dedup exact collisions.
  const hasNg = (p) => !!(neweggBySku && neweggBySku.get(p.sku));
  products.forEach((p) => { p.pageDesc = buildDesc(p, '', hasNg(p)); });
  groupBy(products, (p) => p.pageDesc).forEach((grp) => {
    if (grp.length === 1) return;
    const tokens = assignTokens(grp);
    grp.forEach((p, i) => { p.pageDesc = buildDesc(p, tokens[i], hasNg(p)); });
  });
}

