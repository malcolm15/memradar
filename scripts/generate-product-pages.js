// ------------------------------------------------------------------- slugs
function computeSlug(p) {
  let src = shortName(p);
  const cap = capacityLabel(totalCapacityGB(p.name));
  const spd = p.category === 'ram' ? parseSpeed(p.name) : null;
  if (cap && !src.toLowerCase().includes(cap.toLowerCase())) src += ' ' + cap;
  if (spd && !src.includes(String(spd))) src += ' ' + spd + 'mhz';
  let slug = src.toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
  if (slug.length > 80) {
    slug = slug.slice(0, 80);
    if (slug.includes('-')) slug = slug.slice(0, slug.lastIndexOf('-'));
  }
  return slug;
}

// -------------------------------------------------------- title/desc meta
// Bing bands: title 30-60, description 120-160. Both embed a product name
// trimmed independently; descriptions embed live prices so the name budget is
// computed dynamically per product. Collision variants (products that would
// otherwise share a title or description) are differentiated by a real token
// extracted from the full name (speed, CL, color, heatsink, pack), falling
// back to the ASIN's last 4 chars.
const TITLE_SUFFIX = ' Price Tracker | MemRadar'; // 25 chars -> name budget 35 for a <=60 title
const TITLE_NAME_BUDGET = 60 - TITLE_SUFFIX.length;
const DESC_TARGET = 156; // aim high in-band; the fixed template guarantees >=120

// Trim a string to <=budget at a word boundary (no mid-word cuts).
function capWords(str, budget) {
  if (budget <= 0) return '';
  if (str.length <= budget) return str.trim();
  let s = str.slice(0, budget);
  const sp = s.lastIndexOf(' ');
  if (sp > budget * 0.5) s = s.slice(0, sp);
  return s.trim();
}

function tokenValue(p, type) {
  const n = p.name;
  if (type === 'speed') { const s = parseSpeed(n); return s ? s + 'MHz' : null; }
  if (type === 'cl') { const m = n.match(/\bCL\s?(\d{2})\b/i); return m ? 'CL' + m[1] : null; }
  if (type === 'color') { const m = n.match(/\b(Black|White|Gray|Grey|Silver|Green|Blue|Red|Royal)\b/i); return m ? m[1] : null; }
  if (type === 'heatsink') {
    if (/non-?heatsink|without heatsink|w\/o heatsink/i.test(n)) return 'No Heatsink';
    if (/heatsink/i.test(n)) return 'Heatsink';
    return null;
  }
  if (type === 'pack') { const m = n.match(/(\d+)[\s-]?pack/i); return m ? m[1] + '-Pack' : null; }
  return null;
}
// For a collision group, return a distinct token per member. Prefer a real
// attribute where every member has a distinct value; else the ASIN last-4.
function assignTokens(grp) {
  for (const type of ['speed', 'cl', 'color', 'heatsink', 'pack']) {
    const vals = grp.map((p) => tokenValue(p, type));
    if (vals.every(Boolean) && new Set(vals).size === grp.length) return vals;
  }
  return grp.map((p) => p.sku.slice(-4));
}
function groupBy(arr, keyFn) {
  const m = new Map();
  arr.forEach((x) => { const k = keyFn(x); (m.get(k) || m.set(k, []).get(k)).push(x); });
  return [...m.values()];
}

function buildDesc(p, token) {
  const s = p.stats;
  const prefix = 'Track the ';
  // "Daily Amazon price tracking" was doubly stale: the fetch runs every 4
  // hours now, and 151 of 235 PDPs carry a Newegg comparison row. Naming
  // Newegg here would be false on the other 84, so the tail states the
  // cadence and the alert, both true on every page.
  const middle = ' price history. Current price ' + money(s.current) + '. All-time low ' + money(s.atl.price) +
    ' (' + monthYear(s.atl.day) + '). Updated every few hours with free drop alerts.';
  const tok = token ? ' ' + token : '';
  // Budget against the ESCAPED length, not the raw one. Names containing a
  // quote render as &#39; (6 chars for 1), so a raw-length budget silently
  // overshoots the 160-char band - latent until a shorter tail freed enough
  // room to let those characters in. Shrink until the escaped result fits.
  let budget = DESC_TARGET - prefix.length - middle.length - tok.length;
  let out;
  for (;;) {
    out = prefix + capWords(shortName(p), Math.max(6, budget)) + tok + middle;
    if (esc(out).length <= DESC_TARGET || budget <= 6) break;
    budget -= 1;
  }
  return out;
}

// Compute unique, in-band pageTitle + pageDesc for every product (mutates).
function computePageMeta(products) {
  // Titles: base = shortName capped to the name budget; dedup collisions with tokens.
  groupBy(products, (p) => p.category + '|' + capWords(shortName(p), TITLE_NAME_BUDGET)).forEach((grp) => {
    if (grp.length === 1) { grp[0]._titleName = capWords(shortName(grp[0]), TITLE_NAME_BUDGET); return; }
    const tokens = assignTokens(grp);
    grp.forEach((p, i) => {
      const tok = tokens[i];
      p._titleName = (capWords(shortName(p), TITLE_NAME_BUDGET - tok.length - 1) + ' ' + tok).trim();
    });
  });
  products.forEach((p) => { p.pageTitle = p._titleName + TITLE_SUFFIX; });

  // Descriptions: dynamic name budget per product; then dedup exact collisions.
  products.forEach((p) => { p.pageDesc = buildDesc(p, ''); });
  groupBy(products, (p) => p.pageDesc).forEach((grp) => {
    if (grp.length === 1) return;
    const tokens = assignTokens(grp);
    grp.forEach((p, i) => { p.pageDesc = buildDesc(p, tokens[i]); });
  });
}

// --------------------------------------------------------------- data load
// Paginated select. A SHORT PAGE IS TREATED AS END-OF-DATA, which is correct
// for PostgREST but means a transient short response mid-pagination would end
// the loop cleanly with partial results and no error. That did NOT cause the
// 2026-08-26 incident (that run loaded all 77,843 rows; the failure was a
// missing env var), but the exposure is real and silent, so every call now
// reports pages and rows. Pass `label` to make a partial read visible in any
// run's log, and `expected` to fail loudly when a cheap expected count exists.
async function pagedSelect(build, opts = {}) {
  const out = [];
  let pages = 0;
  for (let from = 0; ; from += PAGE) {
    const { data, error } = await build().range(from, from + PAGE - 1);
    if (error) throw error;
    pages++;
    out.push(...data);
    if (data.length < PAGE) break;
  }
  if (opts.label) log(`  ${opts.label}: ${out.length} rows in ${pages} page(s)`);
  if (opts.expected != null && out.length !== opts.expected) {
    throw new Error(`${opts.label || 'pagedSelect'}: expected ${opts.expected} rows, got ${out.length} - refusing to continue on a partial read`);
  }
  return out;
}

// Daily series: last reading of each UTC day, chronological.
function buildDailySeries(rows) {
  const byDay = new Map();
  for (const r of rows) {
    const day = r.fetched_at.slice(0, 10);
    const prev = byDay.get(day);
    if (!prev || r.fetched_at > prev.fetched_at) byDay.set(day, r);
  }
  return [...byDay.entries()]
    .map(([day, r]) => ({ day, price: Number(r.price), inStock: r.in_stock, fetched_at: r.fetched_at }))
    .sort((a, b) => (a.day < b.day ? -1 : 1));
}

// Chart downsample: daily within the last year, weekly 1-3 years back,
// monthly beyond 3 years. Keeps a decade-long history under ~500 points.
function downsampleForChart(series) {
  const now = Date.now();
  const oneYr = now - 365 * DAY_MS;
  const threeYr = now - 3 * 365 * DAY_MS;
  const out = [];
  let lastKey = null;
  for (const pt of series) {
    const t = new Date(pt.day + 'T00:00:00Z').getTime();
    let key;
    if (t >= oneYr) key = pt.day; // daily
    else if (t >= threeYr) key = pt.day.slice(0, 4) + '-w' + Math.floor(t / (7 * DAY_MS)); // weekly
    else key = pt.day.slice(0, 7); // monthly
    if (key === lastKey) out[out.length - 1] = [pt.day, pt.price]; // last of bucket wins
    else out.push([pt.day, pt.price]);
    lastKey = key;
  }
  return out;
}

function computeStats(series) {
  if (!series.length) return null;
  const now = Date.now();
  const current = series[series.length - 1];
  let atl = series[0], ath = series[0];
  for (const pt of series) {
    if (pt.price < atl.price) atl = pt;
    if (pt.price > ath.price) ath = pt;
  }
  const in90 = series.filter((pt) => new Date(pt.day).getTime() >= now - 90 * DAY_MS);
  const avg90 = in90.length ? round2(in90.reduce((a, p) => a + p.price, 0) / in90.length) : null;
  const target30 = now - 30 * DAY_MS;
  let base30 = null, bestDist = Infinity;
  for (const pt of series) {
    const t = new Date(pt.day).getTime();
    if (t >= now - 35 * DAY_MS && t <= now - 25 * DAY_MS) {
      const d = Math.abs(t - target30);
      if (d < bestDist) { bestDist = d; base30 = pt; }
    }
  }
  const change30 = base30 ? round2(((current.price - base30.price) / base30.price) * 100) : null;
  return {
    current: current.price,
    currentDay: current.day,
    atl: { price: atl.price, day: atl.day },
    ath: { price: ath.price, day: ath.day },
    avg90,
    change30,
    base30: base30 ? base30.price : null,
    firstDay: series[0].day,
    days: series.length,
    limited: series.length < 30,
  };
}

