function buildHead(templateHead, ctx) {
  let head = templateHead;
  // Precomputed by computePageMeta: unique + in-band (title 30-60, desc 120-160).
  const title = ctx.p.pageTitle;
  const desc = ctx.p.pageDesc;

  head = head.replace(/<title>[\s\S]*?<\/title>/, `<title>${esc(title)}</title>`);
  head = head.replace(/<meta name="description" content="[^"]*">/, `<meta name="description" content="${esc(desc)}">`);
  // A relisting points its canonical at the product it duplicates, not at
  // itself. The page stays live and fully rendered; this only tells search
  // engines which of the two URLs is the one to index.
  const canonicalUrl = ctx.p._relistingOf
    ? `${SITE}/${ctx.p._relistingOf.category}/${ctx.p._relistingOf.finalSlug}/`
    : ctx.url;
  head = head.replace(/<link rel="canonical" href="[^"]*">/, `<link rel="canonical" href="${canonicalUrl}">`);
  head = head.replace(/<meta property="og:url" content="[^"]*">/, `<meta property="og:url" content="${ctx.url}">`);
  head = head.replace(/<meta property="og:title" content="[^"]*">/, `<meta property="og:title" content="${esc(title)}">`);
  head = head.replace(/<meta property="og:description" content="[^"]*">/, `<meta property="og:description" content="${esc(desc)}">`);
  head = head.replace(/<meta name="twitter:title" content="[^"]*">/, `<meta name="twitter:title" content="${esc(title)}">`);
  head = head.replace(/<meta name="twitter:description" content="[^"]*">/, `<meta name="twitter:description" content="${esc(desc)}">`);
  // INDEX ELIGIBILITY BY DATA DEPTH (R1). The template ships noindex so the
  // template itself is never indexed; generated pages normally strip it. A PDP
  // with under MIN_DAYS_INDEXABLE days of tracked history keeps a noindex
  // instead, upgraded to `noindex,follow` so the page still passes link equity
  // into the catalog. This is recomputed from live data on EVERY regen, so a
  // page flips back to indexable automatically on the first daily run after it
  // crosses the line. Nothing to remember, nothing to clean up.
  head = ctx.stats && ctx.stats.indexable === false
    ? head.replace(/<meta name="robots" content="noindex">/, '<meta name="robots" content="noindex,follow">')
    : head.replace(/<meta name="robots" content="noindex">\s*/, '');

  const product = {
    '@type': 'Product',
    // Concise collision-unique name (same builder as the <title> tag), not the
    // full Amazon title: 116/235 raw titles exceed the ~150-char bound behind
    // Search Console's "Invalid string length in name" flag.
    name: ctx.p._titleName,
    sku: ctx.p.sku,
    description: desc,
    offers: buildJsonLdOffers(ctx),
  };
  const mpn = parseMpn(ctx.p.name);
  if (mpn) product.mpn = mpn;
  if (ctx.p.brand) product.brand = { '@type': 'Brand', name: ctx.p.brand };
  if (ctx.p.image_url) product.image = jsonldImage(ctx.p.image_url);
  const jsonld = {
    '@context': 'https://schema.org',
    '@graph': [
      product,
      {
        '@type': 'BreadcrumbList',
        itemListElement: [
          // Names/URLs mirror the visible breadcrumb exactly (Home / RAM|SSDs / product).
          { '@type': 'ListItem', position: 1, name: 'Home', item: SITE + '/' },
          { '@type': 'ListItem', position: 2, name: ctx.p.category === 'ram' ? 'RAM' : 'SSDs', item: `${SITE}/${ctx.p.category}/` },
          { '@type': 'ListItem', position: 3, name: ctx.short, item: ctx.url },
        ],
      },
    ],
  };
  // JSON.stringify handles quote/ampersand escaping inside values; escape "</"
  // so the serialized JSON can never close the script tag early.
  const jsonldStr = JSON.stringify(jsonld, null, 2).replace(/<\//g, '<\\/');
  head = head.replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>/, `<script type="application/ld+json">\n${jsonldStr}\n  </script>`);
  return head;
}

// ------------------------------------------------- Buy Now retailer rows
// Amazon always; Newegg when a retailer_offers row exists (current-price
// comparison ONLY - history/charts/analysis/alerts stay Amazon/Keepa).
// Order: cheapest in-stock offer first (in-stock beats OOS, then price asc,
// Amazon wins ties for stability). Newegg links wrap the CLEAN stored URL in
// the Rakuten deep link at render time (never stored wrapped).
// Product JSON-LD offers block. Single-retailer pages keep the exact Offer
// shape shipped before Newegg existed (byte-identical output). Two-retailer
// pages get an AggregateOffer whose lowPrice/highPrice are DERIVED from the
// nested offers - never set independently - so the aggregate can't disagree
// with its own offers. pdp-hydrate.js maintains the same invariant when it
// refreshes either retailer's price client-side.
function buildJsonLdOffers(ctx) {
  // Price validity window on the 4-hourly fetch clock: valid from this
  // generation, until the next scheduled fetch. pdp-hydrate.js rolls both
  // forward client-side so a page rendered later never advertises a stale
  // window.
  const validFrom = new Date().toISOString();
  const priceValidUntil = nextFetchIso(new Date());
  const amazon = {
    '@type': 'Offer',
    price: ctx.stats.current,
    priceCurrency: 'USD',
    url: ctx.url,
    availability: ctx.inStock ? 'https://schema.org/InStock' : 'https://schema.org/OutOfStock',
    itemCondition: 'https://schema.org/NewCondition',
    validFrom,
    priceValidUntil,
  };
  const o = ctx.neweggOffer;
  if (!o || o.price == null) return amazon;
  amazon.seller = { '@type': 'Organization', name: 'Amazon' };
  const newegg = {
    '@type': 'Offer',
    price: Number(o.price),
    priceCurrency: 'USD',
    url: ctx.url,
    itemCondition: 'https://schema.org/NewCondition',
    validFrom,
    priceValidUntil,
    seller: { '@type': 'Organization', name: 'Newegg' },
  };
  // in_stock is nullable; unknown makes no availability claim (same rule as
  // the visible stock badge).
  if (o.in_stock != null) newegg.availability = o.in_stock ? 'https://schema.org/InStock' : 'https://schema.org/OutOfStock';
  const prices = [amazon.price, newegg.price];
  return {
    '@type': 'AggregateOffer',
    offerCount: 2,
    lowPrice: Math.min(...prices),
    highPrice: Math.max(...prices),
    priceCurrency: 'USD',
    offers: [amazon, newegg],
  };
}

// SINGLE SOURCE for retailer offers on a PDP: both the header retailer strip
// and the Buy Now table render from this one sorted list, so affiliate
// wrapping, stock semantics, and the sort rule can never diverge between the
// two surfaces. Sort: in-stock first, then cheapest, then Amazon before
// Newegg as a stable tiebreak.
function retailerList(ctx, affUrl) {
  const rows = [{
    retailer: 'Amazon',
    key: 'amazon',
    price: ctx.stats.current,
    priceId: ' id="pdpBuyPrice"',
    stockId: ' id="pdpAmazonStock"',
    stripPriceId: ' id="pdpStripAmazonPrice"',
    inStock: !!ctx.inStock,
    href: affUrl,
    btn: 'View on Amazon →',
    order: 0,
  }];
  if (ctx.neweggOffer) {
    const o = ctx.neweggOffer;
    rows.push({
      retailer: 'Newegg',
      key: 'newegg',
      price: o.price != null ? Number(o.price) : null,
      priceId: ' id="pdpNeweggPrice"',
      stockId: ' id="pdpNeweggStock"',
      stripPriceId: ' id="pdpStripNeweggPrice"',
      inStock: o.in_stock, // true | false | null (unknown -> no badge, no claim)
      href: neweggDeepLink(o.product_url),
      btn: 'View on Newegg →',
      order: 1,
    });
  }
  rows.sort((a, b) =>
    ((b.inStock === true ? 1 : 0) - (a.inStock === true ? 1 : 0)) ||
    ((a.price == null ? Infinity : a.price) - (b.price == null ? Infinity : b.price)) ||
    (a.order - b.order));
  return rows;
}

// Header retailer strip: the prominent purchase affordance, directly under
// the spec summary / capacity chips. Same links and sort as the Buy Now
// table (both consume retailerList). Out-of-stock retailers stay visible but
// muted and labelled - hiding them would silently answer "is it available
// elsewhere?" with nothing, which reads as "we never checked".
function buildRetailerStrip(rows) {
  if (!rows.length) return '';
  const btns = rows.map((r) => {
    const oos = r.inStock === false;
    return `<a href="${esc(r.href)}" class="pdp-rstrip-btn pdp-rstrip-btn--${r.key}${oos ? ' pdp-rstrip-btn--oos' : ''}" target="_blank" rel="nofollow sponsored noopener noreferrer">` +
      `<span class="pdp-rstrip-name">${r.retailer}</span>` +
      `<span class="pdp-rstrip-sep" aria-hidden="true">·</span>` +
      `<span class="pdp-rstrip-price"${r.stripPriceId}>${money(r.price)}</span>` +
      (oos ? `<span class="pdp-rstrip-oos">Out of stock</span>` : '') +
      `</a>`;
  }).join('');
  return `\n            <div class="pdp-rstrip" role="group" aria-label="Buy from retailer">${btns}</div>`;
}

function buildRetailerRows(ctx, affUrl) {
  const rows = retailerList(ctx, affUrl);
  const stockBadge = (r) => {
    if (r.inStock === true) return `<span${r.stockId} class="pdp-stock pdp-stock--in">In Stock</span>`;
    if (r.inStock === false) return `<span${r.stockId} class="pdp-stock pdp-stock--out">Out of Stock</span>`;
    return `<span${r.stockId} class="pdp-stock"></span>`; // unknown: no claim
  };
  return rows.map((r) => `              <tr>
                <td class="pdp-retailer-name">${r.retailer}</td>
                <td class="pdp-retailer-price"${r.priceId}>${money(r.price)}</td>
                <td class="pdp-retailer-stock">${stockBadge(r)}</td>
                <td class="pdp-retailer-action"><a href="${esc(r.href)}" class="pdp-buy-btn pdp-buy-btn--${r.key}${r.inStock === false ? ' pdp-buy-btn--oos' : ''}" target="_blank" rel="nofollow sponsored noopener noreferrer">${r.btn}</a></td>
              </tr>`).join('\n');
}

